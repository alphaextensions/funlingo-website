// Generates app/i18n/pages/<page>/index.ts for every page folder: statically
// imports en.ts plus every <locale>.json present and exports `getStrings`.
// Static imports keep this compatible with `output: "export"`.
//
//   node scripts/gen-page-dicts.mjs

import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const ROOT = "app/i18n/pages";
for (const page of readdirSync(ROOT)) {
  const dir = join(ROOT, page);
  if (!statSync(dir).isDirectory()) continue;
  const locales = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -5))
    .sort();
  const ident = (code) => "l_" + code.replace(/-/g, "_");
  const out = [
    "// AUTO-GENERATED by scripts/gen-page-dicts.mjs — do not edit by hand.",
    'import { makePageDict } from "@/app/i18n/page-dict";',
    'import { en } from "./en";',
    ...locales.map((c) => `import ${ident(c)} from "./${c}.json";`),
    "",
    "export type Strings = typeof en;",
    "export { en };",
    "export const getStrings = makePageDict<Strings>(en, {",
    ...locales.map((c) => `  ${JSON.stringify(c)}: ${ident(c)},`),
    "});",
    "",
  ].join("\n");
  writeFileSync(join(dir, "index.ts"), out);
  console.log(`[gen-page-dicts] ${page}: ${locales.length} locale(s)`);
}
